//! Only worker-owned TCP connections. Native IO is isolated from the capture poll thread.
use super::{shared::*, source::Ticket, *};
use loom_eth_capture::{CaptureSource, Direction, SimTapSource, SocketConnection, StopSignal, TcpFlags};
use std::{
    io::Write as _,
    net::{IpAddr, Ipv4Addr, Ipv6Addr, SocketAddr, TcpStream},
    sync::mpsc,
    time::Instant,
};
/// All open connections (including transient sends) per channel; reject a new peer at the ceiling.
pub const MAX_TCP_CONNECTIONS: usize = 4;
/// Idle owned connections close after 30 seconds; activity is payload send, not captured traffic.
pub const CAP_TCP_IDLE_NS: u64 = 30_000_000_000;
/// Dedicated native send queue; newest rejected, additionally charged to the shared TX byte budget.
pub const MAX_TCP_COMMANDS: usize = 4;
/// Native connect cannot be interrupted in safe std; bound the blocking interval to 50 ms.
pub const CAP_TCP_CONNECT: Duration = Duration::from_millis(50);
/// Nonblocking payload send deadline (partial completion is outcome_unknown, never retried).
pub const CAP_TCP_WRITE: Duration = Duration::from_millis(50);
/// Bounded native service wake/STOP cadence.
pub const CAP_TCP_POLL: Duration = Duration::from_millis(2);
/// One synthetic exchange: handshake 3 + data 1 + teardown 3 frames; reject before exceeding.
pub const MAX_TCP_EXCHANGE_FRAMES: usize = 7;
#[derive(Debug)]
pub(super) struct NativeTcp {
    tx: mpsc::SyncSender<Box<Ticket>>,
    stop: Arc<AtomicBool>,
    thread: Option<JoinHandle<()>>,
}
#[derive(Debug)]
struct NativeConnection {
    to: SocketAddr,
    stream: TcpStream,
    last_ns: u64,
    meta: TxMeta,
    shared: Arc<Shared>,
    observation: Arc<Mutex<TxObservation>>,
}
impl NativeTcp {
    pub fn new(signal: StopSignal, cx: WorkerCtx) -> Result<Self, WorkerError> {
        let (tx, rx) = mpsc::sync_channel::<Box<Ticket>>(MAX_TCP_COMMANDS);
        let stop = Arc::new(AtomicBool::new(false));
        let flag = stop.clone();
        let thread = std::thread::Builder::new()
            .name("loom-eth-tcp".into())
            .spawn(move || {
                let mut pool = Vec::<NativeConnection>::with_capacity(MAX_TCP_CONNECTIONS);
                while !flag.load(Ordering::Acquire) && !signal.is_stopped() {
                    let now = cx.clock().mono_ns();
                    pool.retain(|c| {
                        if now.saturating_sub(c.last_ns) < CAP_TCP_IDLE_NS {
                            return true;
                        }
                        // Preserve ownership of the FIN generated by closing an idle socket.
                        if let Ok(local) = c.stream.local_addr() {
                            let mut recent = lock(&c.shared.recent);
                            let o = recent.tcp_attempt(c.to, c.meta.clone(), now);
                            recent.tcp_bound(&o, local, c.to);
                            // This is an old completed send: keep its observed state monotone.
                            let prior = lock(&c.observation).seq;
                            let mut observation = lock(&o);
                            observation.sent = true;
                            observation.seq = prior;
                        }
                        false
                    });
                    match rx.recv_timeout(CAP_TCP_POLL) {
                        Ok(mut t) => {
                            let result = send_native(&mut pool, &mut t, &signal, &flag);
                            match result {
                                Ok(observation) => {
                                    let mut o = lock(&observation);
                                    t.meta.row.write_state = "sent".into();
                                    t.meta.row.observed_src_seq = o.seq.map(loom_proto::num::U64);
                                    let ok =
                                        t.meta
                                            .emit(&t.emitter, &t.shared.metrics, WriteState::Sent, o.seq);
                                    o.sent = true;
                                    t.finish(Ok(()), ok);
                                }
                                Err((e, 0)) => t.finish(Err(e), false),
                                Err((e, n)) => {
                                    t.meta.emit(
                                        &t.emitter,
                                        &t.shared.metrics,
                                        WriteState::OutcomeUnknown,
                                        None,
                                    );
                                    if let Some(c) = t.complete.take() {
                                        c.finish(WriteOutcome {
                                            state: WriteState::OutcomeUnknown,
                                            detail: json!({"accepted_bytes":n}),
                                            error: Some(e),
                                        });
                                    }
                                }
                            }
                        }
                        Err(mpsc::RecvTimeoutError::Timeout) => (),
                        Err(mpsc::RecvTimeoutError::Disconnected) => break,
                    }
                }
                // Dropping rx fails every queued ticket; dropping pool closes only owned sockets.
            })
            .map_err(|e| error(ErrorCode::Internal, e.to_string()))?;
        Ok(Self {
            tx,
            stop,
            thread: Some(thread),
        })
    }
    pub fn submit(&self, t: Box<Ticket>) {
        if let Err(e) = self.tx.try_send(t) {
            let (mut t, code) = match e {
                mpsc::TrySendError::Full(t) => (t, ErrorCode::WorkerBusy),
                mpsc::TrySendError::Disconnected(t) => (t, ErrorCode::NotOpen),
            };
            t.finish(Err(error(code, "owned TCP send queue full/closed")), false);
        }
    }
}
impl Drop for NativeTcp {
    fn drop(&mut self) {
        self.stop.store(true, Ordering::Release);
        if let Some(t) = self.thread.take() {
            let _ = t.join();
        }
    }
}
fn permitted(t: &Ticket, signal: &StopSignal, flag: &AtomicBool) -> Result<(), WorkerError> {
    if signal.is_stopped() || flag.load(Ordering::Acquire) {
        return Err(error(ErrorCode::NotOpen, "TCP owner stopping"));
    }
    if t.cx.latch().is_on() && t.meta.origin != Origin::User {
        return Err(error(ErrorCode::Stopped, "STOP latched before TCP IO"));
    }
    if t.deadline_ns > 0 && t.cx.clock().mono_ns() >= t.deadline_ns {
        return Err(error(ErrorCode::Timeout, "TCP deadline expired"));
    }
    Ok(())
}
fn send_native(
    pool: &mut Vec<NativeConnection>,
    t: &mut Ticket,
    signal: &StopSignal,
    flag: &AtomicBool,
) -> Result<Arc<Mutex<TxObservation>>, (WorkerError, usize)> {
    let (to, keep_open) = match t.op {
        super::source::Operation::Tcp { to, keep_open } => (to, keep_open),
        _ => return Err((error(ErrorCode::Internal, "TCP operation expected"), 0)),
    };
    permitted(t, signal, flag).map_err(|e| (e, 0))?;
    let index = pool.iter().position(|c| c.to == to);
    if index.is_none() && pool.len() >= MAX_TCP_CONNECTIONS {
        return Err((
            error(ErrorCode::WorkerBusy, "four owned TCP connections already open"),
            0,
        ));
    }
    let observation = lock(&t.shared.recent).tcp_attempt(to, t.meta.clone(), t.cx.clock().mono_ns());
    let mut c = if let Some(i) = index {
        pool.swap_remove(i)
    } else {
        let stream = TcpStream::connect_timeout(&to, CAP_TCP_CONNECT)
            .map_err(|e| (error(ErrorCode::NotOpen, e.to_string()), 0))?;
        stream
            .set_nonblocking(true)
            .map_err(|e| (error(ErrorCode::NotOpen, e.to_string()), 0))?;
        NativeConnection {
            to,
            stream,
            last_ns: t.cx.clock().mono_ns(),
            meta: t.meta.clone(),
            shared: t.shared.clone(),
            observation: observation.clone(),
        }
    };
    permitted(t, signal, flag).map_err(|e| (e, 0))?;
    let local = c
        .stream
        .local_addr()
        .map_err(|e| (error(ErrorCode::NotOpen, e.to_string()), 0))?;
    // Mark the owned tuple before the first write: captured partial sends must not become device evidence.
    lock(&t.shared.recent).tcp_bound(&observation, local, to);
    let start = Instant::now();
    let mut n = 0;
    while n < t.bytes.len() {
        permitted(t, signal, flag).map_err(|e| (e, n))?;
        if start.elapsed() >= CAP_TCP_WRITE {
            return Err((
                error(
                    if n == 0 {
                        ErrorCode::Timeout
                    } else {
                        ErrorCode::Partial
                    },
                    "TCP write deadline; connection closed, no retry",
                ),
                n,
            ));
        }
        match c.stream.write(&t.bytes[n..]) {
            Ok(0) => {
                return Err((
                    error(
                        if n == 0 {
                            ErrorCode::NotOpen
                        } else {
                            ErrorCode::Partial
                        },
                        "TCP peer closed during send",
                    ),
                    n,
                ));
            }
            Ok(k) => n += k,
            Err(e) if e.kind() == std::io::ErrorKind::WouldBlock => std::thread::sleep(CAP_TCP_POLL),
            Err(e) if e.kind() == std::io::ErrorKind::Interrupted => (),
            Err(e) => {
                return Err((
                    error(
                        if n == 0 {
                            ErrorCode::NotOpen
                        } else {
                            ErrorCode::Partial
                        },
                        e.to_string(),
                    ),
                    n,
                ));
            }
        }
    }
    c.last_ns = t.cx.clock().mono_ns();
    c.meta = t.meta.clone();
    c.observation = observation.clone();
    c.meta.row.write_state = "sent".into();
    if keep_open {
        pool.push(c);
    }
    Ok(observation)
}
#[derive(Debug)]
struct VirtualConnection {
    wire: SocketConnection,
    last_ns: u64,
    meta: TxMeta,
}
#[derive(Debug)]
pub(super) struct VirtualFrame {
    pub bytes: Vec<u8>,
    pub meta: Option<TxMeta>,
}
#[derive(Debug)]
pub(super) struct VirtualTcp {
    tap: SimTapSource,
    pool: Vec<VirtualConnection>,
    port: u16,
}
impl Default for VirtualTcp {
    fn default() -> Self {
        Self {
            tap: SimTapSource::new(),
            pool: Vec::with_capacity(MAX_TCP_CONNECTIONS),
            port: 49152,
        }
    }
}
impl VirtualTcp {
    fn push(
        &self,
        c: SocketConnection,
        dir: Direction,
        data: &[u8],
        flags: TcpFlags,
    ) -> Result<(), WorkerError> {
        self.tap
            .handle()
            .push_tcp_socket(c, dir, data, flags)
            .map_err(capture_error)
    }
    fn drain(&mut self, meta: &TxMeta) -> Result<Vec<VirtualFrame>, WorkerError> {
        let mut out = Vec::with_capacity(MAX_TCP_EXCHANGE_FRAMES);
        while let Some(f) = self.tap.next(Duration::ZERO).map_err(capture_error)? {
            if out.len() >= MAX_TCP_EXCHANGE_FRAMES {
                return Err(error(ErrorCode::Internal, "synthetic exchange bound"));
            }
            let own = f.data.get(6..12) == Some(&[2, 0, 0, 0, 0, 1]);
            out.push(VirtualFrame {
                bytes: f.data,
                meta: own.then(|| meta.clone()),
            });
        }
        Ok(out)
    }
    fn close(&mut self, c: VirtualConnection) -> Result<Vec<VirtualFrame>, WorkerError> {
        let fin = TcpFlags {
            syn: false,
            fin: true,
        };
        self.push(c.wire, Direction::Tx, &[], fin)?;
        self.push(c.wire, Direction::Rx, &[], fin)?;
        self.push(c.wire, Direction::Tx, &[], TcpFlags::default())?;
        self.tap.handle().forget_socket_connection(&c.wire);
        self.drain(&c.meta)
    }
    pub fn expire(&mut self, now: u64) -> Result<Vec<VirtualFrame>, WorkerError> {
        // At most four closed connections * three teardown frames, all bounded by the pending queue.
        let mut out = Vec::with_capacity(MAX_TCP_CONNECTIONS * 3);
        let mut i = 0;
        while i < self.pool.len() {
            if now.saturating_sub(self.pool[i].last_ns) >= CAP_TCP_IDLE_NS {
                let c = self.pool.swap_remove(i);
                out.extend(self.close(c)?);
            } else {
                i += 1;
            }
        }
        Ok(out)
    }
    pub fn send(
        &mut self,
        to: SocketAddr,
        bytes: &[u8],
        keep_open: bool,
        meta: TxMeta,
        now: u64,
    ) -> Result<Vec<VirtualFrame>, WorkerError> {
        let i = self.pool.iter().position(|c| c.wire.server == to);
        if i.is_none() && self.pool.len() >= MAX_TCP_CONNECTIONS {
            return Err(error(
                ErrorCode::WorkerBusy,
                "four synthetic TCP connections already open",
            ));
        }
        let mut c = if let Some(i) = i {
            self.pool.swap_remove(i)
        } else {
            let local = SocketAddr::new(
                match to.ip() {
                    IpAddr::V4(_) => IpAddr::V4(Ipv4Addr::new(192, 0, 2, 1)),
                    IpAddr::V6(_) => IpAddr::V6(Ipv6Addr::LOCALHOST),
                },
                self.port,
            );
            self.port = if self.port == u16::MAX {
                49152
            } else {
                self.port + 1
            };
            let c = VirtualConnection {
                wire: SocketConnection {
                    client: local,
                    server: to,
                    client_mac: [2, 0, 0, 0, 0, 1],
                    server_mac: [2, 0, 0, 0, 0, 2],
                },
                last_ns: now,
                meta: meta.clone(),
            };
            let syn = TcpFlags {
                syn: true,
                fin: false,
            };
            self.push(c.wire, Direction::Tx, &[], syn)?;
            self.push(c.wire, Direction::Rx, &[], syn)?;
            self.push(c.wire, Direction::Tx, &[], TcpFlags::default())?;
            c
        };
        self.push(c.wire, Direction::Tx, bytes, TcpFlags::default())?;
        c.last_ns = now;
        c.meta = meta.clone();
        let mut out = self.drain(&meta)?;
        if keep_open {
            self.pool.push(c);
        } else {
            out.extend(self.close(c)?);
        }
        Ok(out)
    }
}
