use crate::*;
use pcap::{Active, Capture, Precision};
use std::{
    fs::{self, File},
    io::Read,
    path::PathBuf,
    sync::atomic::{AtomicU64, Ordering},
    time::{Instant, SystemTime, UNIX_EPOCH},
};
/// Driver buffer request ceiling; reject larger requests (actual OS allocation is not queried).
pub const MAX_KERNEL_BUFFER_BYTES: i32 = 64 * 1024 * 1024;
/// Probe directory collision attempts; fail closed after this bound.
pub const MAX_PRECISION_PROBES: usize = 16;
#[derive(Debug, Clone)]
pub struct LiveConfig {
    pub device: String,
    pub buffer_size: i32,
    pub snaplen: u32,
    pub promisc: bool,
    pub immediate_mode: bool,
}
impl LiveConfig {
    pub fn new(device: impl Into<String>) -> Self {
        Self {
            device: device.into(),
            buffer_size: MAX_KERNEL_BUFFER_BYTES,
            snaplen: 65_535,
            promisc: false,
            immediate_mode: true,
        }
    }
    fn validate(&self) -> Result<()> {
        if self.device.is_empty()
            || self.device.len() > loom_eth_pcapng::MAX_NAME_BYTES
            || self.device.contains('\0')
        {
            return Err(CaptureError::Invalid("live device name"));
        }
        if self.buffer_size <= 0
            || self.buffer_size > MAX_KERNEL_BUFFER_BYTES
            || self.snaplen == 0
            || self.snaplen as usize > MAX_FRAME_BYTES
        {
            return Err(CaptureError::Invalid("live buffer/snaplen"));
        }
        Ok(())
    }
}
pub struct LiveSource {
    capture: Capture<Active>,
    interface: Interface,
    stop: StopSignal,
    pub requested_buffer_size: i32,
    pub precision_fell_back: bool,
}
pub(crate) fn map_error(e: pcap::Error) -> CaptureError {
    let permission = matches!(e, pcap::Error::IoError(std::io::ErrorKind::PermissionDenied))
        || matches!(&e,pcap::Error::ErrnoError(n) if n.0==1 || n.0==13)
        || {
            let text = e.to_string().to_ascii_lowercase();
            [
                "permission denied",
                "operation not permitted",
                "access is denied",
                "access denied",
                "administrator",
            ]
            .iter()
            .any(|s| text.contains(s))
        };
    if permission {
        CaptureError::Permission(e.to_string())
    } else {
        CaptureError::Backend(e.to_string())
    }
}
fn open(config: &LiveConfig, precision: Precision) -> Result<Capture<Active>> {
    Capture::from_device(config.device.as_str())
        .map_err(map_error)?
        .buffer_size(config.buffer_size)
        .snaplen(config.snaplen as i32)
        .promisc(config.promisc)
        .precision(precision)
        .immediate_mode(config.immediate_mode)
        .timeout(1)
        .open()
        .map_err(map_error)
}
// pcap 2.5.0's safe precision setter discards the libpcap return code and exposes no
// getter. A savefile header generated by the SAME active handle provides a safe
// authoritative precision probe without unsafe/FFI or sending/capturing a packet.
// It writes only a 24-byte global header in a private temporary directory.
#[derive(Debug)]
struct ProbeDir(PathBuf);
impl Drop for ProbeDir {
    fn drop(&mut self) {
        let _ = fs::remove_file(self.0.join("header.pcap"));
        let _ = fs::remove_dir(&self.0);
    }
}
fn probe_dir() -> Result<ProbeDir> {
    static NEXT: AtomicU64 = AtomicU64::new(0);
    for _ in 0..MAX_PRECISION_PROBES {
        let stamp = SystemTime::now()
            .duration_since(UNIX_EPOCH)
            .map_or(0, |d| d.as_nanos());
        let path = std::env::temp_dir().join(format!(
            "loom-pcap-precision-{}-{stamp}-{}",
            std::process::id(),
            NEXT.fetch_add(1, Ordering::Relaxed)
        ));
        let mut builder = fs::DirBuilder::new();
        #[cfg(unix)]
        {
            use std::os::unix::fs::DirBuilderExt;
            builder.mode(0o700);
        }
        match builder.create(&path) {
            Ok(()) => return Ok(ProbeDir(path)),
            Err(e) if e.kind() == std::io::ErrorKind::AlreadyExists => continue,
            Err(e) => return Err(e.into()),
        }
    }
    Err(CaptureError::Limit("precision probe directory collisions"))
}
fn actual_precision(capture: &Capture<Active>) -> Result<(TimestampResolution, u32)> {
    let dir = probe_dir()?;
    let path = dir.0.join("header.pcap");
    let mut dump = capture.savefile(&path).map_err(map_error)?;
    dump.flush().map_err(map_error)?;
    drop(dump);
    let mut header = [0; 24];
    File::open(path)?.read_exact(&mut header)?;
    let magic: [u8; 4] = header[..4]
        .try_into()
        .map_err(|_| CaptureError::Invalid("pcap header"))?;
    let raw: [u8; 4] = header[16..20]
        .try_into()
        .map_err(|_| CaptureError::Invalid("pcap snaplen"))?;
    let snaplen = if magic[0] == 0xa1 {
        u32::from_be_bytes(raw)
    } else {
        u32::from_le_bytes(raw)
    };
    match magic {
        [0x4d, 0x3c, 0xb2, 0xa1] | [0xa1, 0xb2, 0x3c, 0x4d] => Ok((TimestampResolution::NANO, snaplen)),
        [0xd4, 0xc3, 0xb2, 0xa1] | [0xa1, 0xb2, 0xc3, 0xd4] => Ok((TimestampResolution::MICRO, snaplen)),
        _ => Err(CaptureError::Backend("unknown pcap dump precision magic".into())),
    }
}
/// BPF expression ceiling; reject before passing to libpcap.
pub const MAX_BPF_BYTES: usize = 8192;
pub(crate) fn validate_bpf(expr: &str) -> Result<()> {
    if expr.len() > MAX_BPF_BYTES || expr.contains('\0') {
        return Err(CaptureError::Bpf {
            msg: "BPF exceeds 8 KiB or contains NUL".into(),
        });
    }
    Ok(())
}
fn bpf_error(e: pcap::Error) -> CaptureError {
    CaptureError::Bpf { msg: e.to_string() }
}
impl LiveSource {
    /// Install an optimized capture filter. An empty expression explicitly clears it.
    pub fn set_bpf(&mut self, expr: &str) -> Result<()> {
        validate_bpf(expr)?;
        self.capture.filter(expr, true).map_err(bpf_error)
    }
    pub fn open(config: LiveConfig) -> Result<Self> {
        config.validate()?;
        let (mut capture, resolution, snaplen, fell_back) = match open(&config, Precision::Nano) {
            Ok(capture) => {
                let (res, snaplen) = actual_precision(&capture)?;
                if res == TimestampResolution::NANO {
                    (capture, res, snaplen, false)
                } else {
                    drop(capture);
                    let c = open(&config, Precision::Micro)?;
                    let (res, snaplen) = actual_precision(&c)?;
                    if res != TimestampResolution::MICRO {
                        return Err(CaptureError::Backend("microsecond fallback not confirmed".into()));
                    }
                    (c, res, snaplen, true)
                }
            }
            Err(e @ CaptureError::Permission(_)) => return Err(e),
            Err(_) => {
                let c = open(&config, Precision::Micro)?;
                let (res, snaplen) = actual_precision(&c)?;
                if res != TimestampResolution::MICRO {
                    return Err(CaptureError::Backend("microsecond fallback not confirmed".into()));
                }
                (c, res, snaplen, true)
            }
        };
        let linktype =
            u16::try_from(capture.get_datalink().0).map_err(|_| CaptureError::Invalid("live linktype"))?;
        if snaplen == 0 || snaplen as usize > MAX_FRAME_BYTES {
            return Err(CaptureError::Invalid("actual live snaplen"));
        }
        capture = capture.setnonblock().map_err(map_error)?;
        Ok(Self {
            capture,
            interface: Interface {
                linktype,
                snaplen,
                name: config.device,
                tsresol: resolution,
            },
            stop: StopSignal::default(),
            requested_buffer_size: config.buffer_size,
            precision_fell_back: fell_back,
        })
    }
}
impl CaptureSource for LiveSource {
    fn interface(&self) -> Interface {
        self.interface.clone()
    }
    fn timestamp_source(&self) -> TimestampSource {
        TimestampSource::PcapHost
    }
    fn set_stop_signal(&mut self, s: StopSignal) {
        self.stop = s;
    }
    fn next(&mut self, timeout: Duration) -> Result<Option<RawFrame>> {
        let start = Instant::now();
        loop {
            if self.stop.is_stopped() {
                return Ok(None);
            }
            match self.capture.next_packet() {
                Ok(p) => {
                    let sec = u128::try_from(p.header.ts.tv_sec)
                        .map_err(|_| CaptureError::Invalid("negative capture timestamp"))?;
                    let fraction = u64::try_from(p.header.ts.tv_usec)
                        .map_err(|_| CaptureError::Invalid("negative capture timestamp fraction"))?;
                    let scale = if self.interface.tsresol == TimestampResolution::NANO {
                        1_000_000_000
                    } else {
                        1_000_000
                    };
                    if fraction >= scale || p.data.len() > MAX_FRAME_BYTES {
                        return Err(CaptureError::Invalid("live packet timestamp/size"));
                    }
                    let raw = RawFrame {
                        ts_ns: sec * 1_000_000_000 + self.interface.tsresol.to_ns(fraction),
                        caplen: p.header.caplen,
                        origlen: p.header.len,
                        data: p.data.to_vec(),
                        interface_id: 0,
                        section_index: 0,
                        interface: self.interface.clone(),
                        comments: Vec::new(),
                        meta: None,
                    };
                    raw.validate()?;
                    return Ok(Some(raw));
                }
                Err(pcap::Error::TimeoutExpired) => {
                    let remaining = timeout.saturating_sub(start.elapsed());
                    if remaining.is_zero() {
                        return Ok(None);
                    }
                    self.stop.wait(remaining.min(Duration::from_millis(1)));
                }
                Err(e) => return Err(map_error(e)),
            }
        }
    }
    fn stats(&mut self) -> DropStats {
        match self.capture.stats() {
            Ok(s) => DropStats {
                availability: StatsAvailability::Partial,
                recv: s.received.into(),
                // Known libpcap backends provide OS-buffer drops; if_drop=0 is
                // conservatively unknown because pcap cannot report support flags.
                kernel_drop: if cfg!(any(target_os = "linux", target_os = "macos", windows)) {
                    Some(s.dropped.into())
                } else {
                    None
                },
                if_drop: if s.if_dropped > 0 {
                    Some(s.if_dropped.into())
                } else {
                    None
                },
            },
            Err(_) => DropStats::UNAVAILABLE,
        }
    }
    fn send(&mut self, frame: &[u8]) -> Result<()> {
        if frame.len() > MAX_FRAME_BYTES {
            return Err(CaptureError::Limit("send bytes"));
        }
        self.capture.sendpacket(frame).map_err(map_error)
    }
}
impl std::fmt::Debug for LiveSource {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.debug_struct("LiveSource")
            .field("interface", &self.interface)
            .field("requested_buffer_size", &self.requested_buffer_size)
            .field("precision_fell_back", &self.precision_fell_back)
            .finish_non_exhaustive()
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn bpf_compile_without_native_capture() {
        let dead = Capture::dead(pcap::Linktype::ETHERNET).expect("dead handle");
        validate_bpf("udp port 30490").expect("bounded");
        let bpf = dead.compile("udp port 30490", true).expect("valid optimized BPF");
        assert!(!bpf.filter(&[0; 64]));
        let err = dead
            .compile("udp and and (", true)
            .map(|_| ())
            .map_err(bpf_error)
            .expect_err("bad syntax");
        assert!(matches!(err, CaptureError::Bpf { .. }));
        assert!(validate_bpf("udp\0tcp").is_err());
        assert!(validate_bpf(&"x".repeat(MAX_BPF_BYTES + 1)).is_err());
    }
    #[test]
    fn permission_error_is_separate() {
        assert!(matches!(
            map_error(pcap::Error::PcapError("/dev/bpf0: Permission denied".into())),
            CaptureError::Permission(_)
        ));
    }
    #[test]
    #[ignore = "requires human-configured BPF/Npcap/capabilities and an explicit interface"]
    fn actual_live_open() {
        let device = std::env::var("LOOM_TEST_INTERFACE").expect("explicit interface required");
        let mut source = LiveSource::open(LiveConfig::new(device)).expect("configured live capture");
        assert!(source.interface.snaplen > 0);
        source.set_bpf("udp port 30490").expect("install optimized BPF");
        assert!(matches!(
            source.set_bpf("udp and and ("),
            Err(CaptureError::Bpf { .. })
        ));
    }
}
