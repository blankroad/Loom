import fs from 'node:fs/promises';
import assert from 'node:assert/strict';
import {compile} from 'json-schema-to-typescript';
import Ajv2020 from 'ajv/dist/2020.js';
const schema=JSON.parse(await fs.readFile('schema-probe/out/schema.json','utf8'));
const fixture=JSON.parse(await fs.readFile('schema-probe/out/fixture.json','utf8'));
const output=await compile(schema,'WireEvent',{bannerComment:'/* Generated by schema probe; do not edit. */'});
await fs.writeFile('schema-probe/out/from-schema.ts',output);
const validate=new Ajv2020({strict:true}).compile(schema);
assert.equal(validate(fixture),true,JSON.stringify(validate.errors));
assert.equal(fixture.payload.seq,'18446744073709551615');
assert.equal(BigInt(fixture.payload.seq),(1n<<64n)-1n);
assert.equal(fixture.payload.mono_ns,'9007199254740993');
const badNumeric=structuredClone(fixture);badNumeric.payload.seq=18446744073709551615;
assert.equal(validate(badNumeric),false);
const badTag=structuredClone(fixture);badTag.kind='unknown.event';assert.equal(validate(badTag),false);
const missing=structuredClone(fixture);delete missing.payload.data_hex;assert.equal(validate(missing),false);
await fs.writeFile('schema-probe/out/consumer.ts','import type {WireEvent} from "./from-schema";\nconst value:WireEvent = '+JSON.stringify(fixture)+';\nconsole.log(value);\n');
const result={schema_draft:schema.$schema,valid_fixture:true,u64_max_preserved:true,above_2_53_preserved:true,numeric_seq_rejected:true,unknown_tag_rejected:true,missing_required_rejected:true,validation:'Ajv 2020 strict',typescript:JSON.parse(await fs.readFile('node_modules/typescript/package.json','utf8')).version,scope:'Tagged enum + decimal-string newtype + optional field only; not all serde attributes, numeric string syntax/range, or full Loom schema'};
await fs.writeFile('schema-probe/out/result.json',JSON.stringify(result,null,2));
console.log(result);
